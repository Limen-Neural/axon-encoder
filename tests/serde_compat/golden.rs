#[test]
fn serde_compat_poisson_config_only() {
    // No RNG state is persisted, and no spike train is generated by this test.
    let file = "v0.5/poisson.json";
    let restored: PoissonEncoder = read_fixture(file, "v0.5 writer -> HEAD reader");
    assert_eq!(
        restored.num_steps, 17,
        "{file} (v0.5 writer -> HEAD reader)"
    );
    assert_json(&PoissonEncoder::new(17), file, "HEAD writer -> v0.5 golden");
}
