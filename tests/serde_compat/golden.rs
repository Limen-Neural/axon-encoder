//! Each expected value is built independently of the committed JSON. Field
//! renames, omissions, new fields, and changes to state interpretation must fail.

use axon_encoder::prelude::*;

use super::{assert_golden, assert_json, read_fixture};

macro_rules! golden {
    ($name:ident, $type:ty, $file:literal, $expected:expr) => {
        #[test]
        fn $name() {
            let expected: $type = $expected;
            assert_golden(concat!("v0.5/", $file, ".json"), expected);
        }
    };
}

